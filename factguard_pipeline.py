#!/usr/bin/env python3
import sys
import re
import json
import warnings
warnings.filterwarnings("ignore")

import torch
import wikipedia
try:
    from ddgs import DDGS
except ImportError:
    from duckduckgo_search import DDGS

from transformers import AutoModelForCausalLM, AutoTokenizer
from peft import PeftModel

BASE_MODEL = "Qwen/Qwen2.5-1.5B-Instruct"
ADAPTER_PATH = "sriharish00u/factguard-slm-adapter"

print("=================================================================")
print("           FactGuard End-to-End Autonomous Pipeline")
print("=================================================================")
print("--> Loading Base Model & LoRA Adapter on CPU...")

tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, trust_remote_code=True)
base_model = AutoModelForCausalLM.from_pretrained(
    BASE_MODEL,
    torch_dtype=torch.bfloat16,
    low_cpu_mem_usage=True,
    device_map="cpu",
    trust_remote_code=True
)
model = PeftModel.from_pretrained(base_model, ADAPTER_PATH)
model.eval()
print("--> FactGuard Engine Ready!\n")

SYS_DECOMPOSER = (
    "You are FactGuard Decomposer. Given an input text generated by an AI assistant, "
    "break down the assertions into verifiable atomic claims. For each claim, output a "
    "focused search query to retrieve authoritative evidence."
)

SYS_EVALUATOR = (
    "You are FactGuard Evaluator & Correction Gate. Analyze atomic claims alongside retrieved evidence. "
    "For each claim, decide status: SUPPORTED, CONTRADICTED, or UNVERIFIABLE. "
    "If any claim is CONTRADICTED, provide a structured prompt patch explaining the hallucination "
    "and directing the external model how to regenerate accurately."
)

def query_model(system_prompt: str, user_content: str, max_tokens: int = 400) -> str:
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content}
    ]
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(prompt, return_tensors="pt")
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=max_tokens,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id
        )
    return tokenizer.decode(out[0][inputs.input_ids.shape[1]:], skip_special_tokens=True).strip()

def extract_json(raw_text: str):
    """Safely extracts JSON from model output."""
    try:
        match = re.search(r"(\{.*\})", raw_text, re.DOTALL)
        if match:
            return json.loads(match.group(1))
        return json.loads(raw_text)
    except Exception:
        return None

def research_claim(query: str) -> str:
    """Executes multi-source tool search: Wikipedia summary fallback to DDGS web search."""
    # 1. Wikipedia Search
    try:
        results = wikipedia.search(query, results=1)
        if results:
            summary = wikipedia.summary(results[0], sentences=2)
            if summary and len(summary.strip()) > 30:
                return f"[Wikipedia: {results[0]}] {summary.strip()}"
    except Exception:
        pass

    # 2. DuckDuckGo Search
    try:
        ddgs = DDGS()
        ddg_results = list(ddgs.text(query, max_results=2))
        if ddg_results:
            snippets = " ".join([r.get("body", "") for r in ddg_results if r.get("body")])
            if snippets:
                return f"[Web Search] {snippets[:400]}"
    except Exception:
        pass

    return "No verified external documentation found for this query."

def run_factguard_pipeline(llm_response: str):
    print("="*65)
    print("STAGE 1: INPUT LLM RESPONSE")
    print("="*65)
    print(f'"{llm_response}"\n')

    # Step 1: Decompose
    print("--> [FactGuard] Splitting response into atomic claims & search queries...")
    stage1_prompt = f"Decompose the following text into atomic claims and generate research queries:\n\n{llm_response}"
    raw_decomposition = query_model(SYS_DECOMPOSER, stage1_prompt)
    decomp_json = extract_json(raw_decomposition)

    if not decomp_json or "claims" not in decomp_json:
        print("[!] Raw output fallback:")
        claims_list = [{"claim_id": "c1", "claim": llm_response, "search_query": llm_response[:60]}]
    else:
        claims_list = decomp_json["claims"]

    print(f"--> Extracted {len(claims_list)} atomic claim(s):")
    for c in claims_list:
        print(f"   [{c.get('claim_id')}] Claim: {c.get('claim')}")
        print(f"         Query: {c.get('search_query')}")
    print()

    # Step 2: Research Tools Execution
    print("="*65)
    print("STAGE 2: CALLING RESEARCH TOOLS")
    print("="*65)
    evaluated_claims = []
    for c in claims_list:
        cid = c.get("claim_id", "c1")
        claim_text = c.get("claim", "")
        query = c.get("search_query", claim_text)

        print(f"--> [Tool] Searching evidence for [{cid}]: '{query}'...")
        evidence = research_claim(query)
        print(f"    Evidence found: {evidence[:120]}...")
        evaluated_claims.append({
            "claim_id": cid,
            "claim": claim_text,
            "evidence": evidence
        })
    print()

    # Step 3: FactGuard Evaluation & Gate
    print("="*65)
    print("STAGE 3: FACTGUARD VERIFICATION & VERDICT")
    print("="*65)
    eval_payload = {"claims": evaluated_claims}
    stage3_prompt = (
        "Evaluate the following claims against the provided evidence and determine if any hallucination occurred:\n\n"
        + json.dumps(eval_payload, indent=2)
    )
    raw_eval = query_model(SYS_EVALUATOR, stage3_prompt)
    eval_json = extract_json(raw_eval)

    # Step 4: User-Friendly Output Presentation
    print("\n" + "#"*65)
    print("                   FINAL VERIFICATION RESULT")
    print("#"*65)

    if eval_json:
        verdict = eval_json.get("verdict", "UNKNOWN")
        is_correct = (verdict.upper() == "VERIFIED")

        if is_correct:
            print("STATUS: ✅ CORRECT (NO HALLUCINATIONS DETECTED)")
            print("\nSafe to return response directly to user:")
            print(f'"{llm_response}"')
        else:
            print("STATUS: ❌ NOT CORRECT (HALLUCINATION DETECTED)")
            print("\nBreakdown of Claims:")
            for ev in eval_json.get("evaluations", []):
                st = ev.get("status", "")
                icon = "✅" if st == "SUPPORTED" else "❌"
                print(f"  {icon} [{ev.get('claim_id')}]: {st}")
                print(f"     Reasoning: {ev.get('reasoning')}")
            
            print("\n" + "-"*65)
            print("ACTION: FIX PROMPT FOR EXTERNAL LLM REGENERATION")
            print("-"*65)
            fix_prompt = eval_json.get("correction_prompt")
            if not fix_prompt:
                fix_prompt = "CRITICAL REVISION: Claims in your response were contradicted by evidence. Please regenerate the text correcting the facts."
            print(fix_prompt)
    else:
        print("Raw Evaluation Output:")
        print(raw_eval)

if __name__ == "__main__":
    if len(sys.argv) > 1:
        test_text = " ".join(sys.argv[1:])
    else:
        test_text = (
            "Marie Curie won the Nobel Prize in Physics in 1903 alongside Pierre Curie, "
            "and later won the Nobel Prize in Literature in 1911 for her autobiographical writings."
        )
    run_factguard_pipeline(test_text)
