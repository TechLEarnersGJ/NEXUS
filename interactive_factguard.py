import sys
import json
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
from peft import PeftModel

BASE_MODEL = "Qwen/Qwen2.5-1.5B-Instruct"
ADAPTER_PATH = "/home/sriharish00u/Desktop/projects/NEXUS/models/factguard_adapter/factguard_adapter"

print("="*65)
print("       FactGuard-SLM Interactive Testing Console")
print("="*65)
print("--> Loading Base Model & LoRA Adapter onto CPU...")

tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, trust_remote_code=True)
base_model = AutoModelForCausalLM.from_pretrained(
    BASE_MODEL,
    torch_dtype=torch.bfloat16,
    low_cpu_mem_usage=True,
    device_map="cpu",
    trust_remote_code=True
)
model = PeftModel.from_pretrained(base_model, ADAPTER_PATH)
model.eval()

print("--> Model Ready! You can now test any custom input.\n")

sys_decomposer = (
    "You are FactGuard Decomposer. Given an input text generated by an AI assistant, "
    "break down the assertions into verifiable atomic claims. For each claim, output a "
    "focused search query to retrieve authoritative evidence."
)

sys_evaluator = (
    "You are FactGuard Evaluator & Correction Gate. Analyze atomic claims alongside retrieved evidence. "
    "For each claim, decide status: SUPPORTED, CONTRADICTED, or UNVERIFIABLE. "
    "If any claim is CONTRADICTED, provide a structured prompt patch explaining the hallucination "
    "and directing the external model how to regenerate accurately."
)

def run_inference(system_prompt, user_content):
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content}
    ]
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(prompt, return_tensors="pt")
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=350,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id
        )
    return tokenizer.decode(out[0][inputs.input_ids.shape[1]:], skip_special_tokens=True)

while True:
    print("\nSelect Mode:")
    print("  1. Decompose Text (Extract Claims & Search Queries)")
    print("  2. Evaluate Evidence & Check Hallucination")
    print("  3. Exit")
    
    choice = input("\nEnter choice (1, 2, or 3): ").strip()
    
    if choice == "1":
        print("\nEnter or paste the LLM text to decompose (press Enter twice to finish):")
        lines = []
        while True:
            line = input()
            if not line:
                break
            lines.append(line)
        text = "\n".join(lines).strip()
        if not text:
            print("No text provided.")
            continue
        
        print("\n[Thinking & Decomposing...]")
        res = run_inference(sys_decomposer, f"Decompose the following text into atomic claims and generate research queries:\n\n{text}")
        print("\n--- FactGuard Output ---")
        print(res)
        print("------------------------")
        
    elif choice == "2":
        claim = input("\nEnter claim: ").strip()
        evidence = input("Enter retrieved evidence: ").strip()
        
        payload = {
            "claims": [
                {
                    "claim_id": "c1",
                    "claim": claim,
                    "evidence": evidence
                }
            ]
        }
        
        print("\n[Evaluating Evidence...]")
        res = run_inference(sys_evaluator, f"Evaluate the following claims against the provided evidence and determine if any hallucination occurred:\n\n{json.dumps(payload, indent=2)}")
        print("\n--- FactGuard Verdict & Correction ---")
        print(res)
        print("--------------------------------------")
        
    elif choice == "3":
        print("Exiting. Bye!")
        break
    else:
        print("Invalid choice, please enter 1, 2, or 3.")
