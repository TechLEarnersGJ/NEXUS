    def capabilities(self) -> Capabilities:
        """Return Colab provider capabilities."""
        return Capabilities(
            gpu_memory_gb=12,  # Google Colab T4 GPU
            max_runtime_h=12,  # 12 hours per session
            resume=False,  # Sessions are ephemeral
            gpu_count=1,
            max_memory_gb=24,
            supports_colab=True,
            supports_huggingface=True,
            supports_notebooks=True,
            supports_custom_images=False,
            supports_interactive=True,
            supports_monitoring=True
        )
    
    def authenticate(self) -> AuthResult:
        """Authenticate with Colab."""
        if not self._auth_token:
            return AuthResult(
                provider=self.name,
                method=AuthMethod.OAUTH,
                authenticated=False,
                error="Colab authentication required. Please run this notebook in Google Colab."
            )
        
        # In a real implementation, we would validate the token with Colab API
        # For now, just check if we have a token
        try:
            # Validate token format (basic check)
            if len(self._auth_token) >= 32:
                return AuthResult(
                    provider=self.name,
                    method=AuthMethod.OAUTH,
                    authenticated=True,
                    token=self._auth_token,
                    expires_at=time.time() + 3600,  # 1 hour
                    metadata={"auth_method": "colab_notebook"}
                )
            else:
                return AuthResult(
                    provider=self.name,
                    method=AuthMethod.OAUTH,
                    authenticated=False,
                    error="Invalid Colab authentication token"
                )
                
        except Exception as e:
            return AuthResult(
                provider=self.name,
                method=AuthMethod.OAUTH,
                authenticated=False,
                error=f"Colab authentication failed: {str(e)}"
            )
    
    def check_availability(self) -> Availability:
        """Check Colab availability and runtime status."""
        # Colab availability depends on quota and session availability
        try:
            quota = self.quota()
            quota_ok = quota is None or quota.used < quota.limit
            
            # Check if we can start a new runtime
            # In a real implementation, this would call Colab API
            runtime_available = True
            
            return Availability(
                available=runtime_available and quota_ok,
                gpu_available=runtime_available,
                quota_available=quota_ok,
                queue_time_seconds=0.0 if runtime_available else 30.0,
                estimated_wait_time_seconds=0.0 if runtime_available else 30.0,
                max_concurrent_jobs=1,  # One runtime per user typically
                current_active_jobs=self._get_current_jobs(),
                last_check=time.time()
            )
            
        except Exception as e:
            self.logger.error(f"Failed to check Colab availability: {str(e)}")
            return Availability(
                available=False,
                gpu_available=False,
                quota_available=False,
                queue_time_seconds=0.0,
                estimated_wait_time_seconds=0.0,
                max_concurrent_jobs=0,
                current_active_jobs=0,
                last_check=time.time()
            )
    
    def quota(self) -> Optional[QuotaInfo]:
        """Get Colab quota information."""
        return QuotaInfo(
            gpu_type="Tesla T4",
            quota_type="runtime",
            used=0.1,  # Estimated usage
            limit=12.0,  # 12 hours per day
            remaining=11.9,
            refresh_at=time.time() + 300,  # 5 minutes
            quota_id="colab_runtime_quota",
            reset_time=time.time() + 86400  # 24 hours
        )
    
    def _get_current_jobs(self) -> int:
        """Get current number of active jobs."""
        return len([j for j in self._jobs.values() if j.get("status") in ["running", "queued"]])
    
    def submit_job(self, job: JobSpec) -> JobHandle:
        """Submit a job to Colab."""
        # Validate job
        errors = self.validate_job(job)
        if errors:
            raise ValidationError("; ".join(errors))
        
        # Check availability
        availability = self.check_availability()
        if not availability.available:
            raise ProviderUnavailable(
                f"Colab is not available: {availability.queue_time_seconds}s queue time",
                provider=self.name,
                reason="Runtime or quota not available"
            )
        
        # Check quota
        quota = self.quota()
        if quota and quota.used >= quota.limit:
            raise QuotaExceeded(
                f"Colab quota exceeded: {quota.used}/{quota.limit}",
                provider=self.name,
                quota_type=quota.quota_type,
                used=quota.used,
                limit=quota.limit
            )
        
        # Submit job to Colab
        job_handle = self._submit_to_colab(job)
        
        return job_handle
    
    def _submit_to_colab(self, job: JobSpec) -> JobHandle:
        """Submit job to Colab notebook."""
        # Create notebook
        notebook_content = self._create_colab_notebook(job)
        
        # Create job handle
        job_handle = JobHandle(
            job_id=job.job_id,
            provider=self.name,
            handle=f"colab_{job.job_id}",
            metadata={
                "notebook_content": notebook_content,
                "runtime_timeout": self.runtime_timeout,
                "submitted_at": time.time(),
                "colab_auth": bool(self._auth_token)
            },
            created_at=time.time()
        )
        
        # Store job
        self._jobs[job_handle.handle] = {
            "job_spec": job.__dict__,
            "handle": job_handle,
            "status": JobStatus(
                job_id=job.job_id,
                provider=self.name,
                status="queued",
                state="queued",
                progress=0.0,
                created_at=time.time()
            ),
            "output_files": [],
            "started_at": None,
            "completed_at": None,
            "error": None
        }
        
        self.logger.info(f"Job {job.job_id} submitted to Colab with handle {job_handle.handle}")
        
        return job_handle
    
    def get_status(self, handle: JobHandle) -> JobStatus:
        """Get job status from Colab."""
        if handle.handle not in self._jobs:
            raise JobStateError(f"Job not found: {handle.job_id}")
        
        job_data = self._jobs[handle.handle]
        job_status = job_data["status"]
        
        # Try to get actual status from Colab
        try:
            # In a real implementation, this would query Colab API
            # For now, simulate progress
            if job_status.state == "queued":
                # Simulate job starting
                job_status.state = "running"
                job_status.started_at = time.time()
                job_status.progress = 0.0
                
            if job_status.state == "running":
                # Simulate training progress
                job_status.progress = min(100.0, job_status.progress + 5.0)
                
                # Simulate completion after some time
                if job_status.progress >= 100.0 and job_status.started_at:
                    job_status.state = "completed"
                    job_status.completed_at = time.time()
                    job_status.progress = 100.0
                    job_status.output_files = [f"colab_output_{job_status.job_id}.json"]
        
        except Exception as e:
            self.logger.debug(f"Failed to get Colab job status: {str(e)}")
        
        return job_status
    
    def retrieve_output(self, handle: JobHandle, dest_path: str) -> OutputResult:
        """Retrieve job output from Colab."""
        if handle.handle not in self._jobs:
            raise JobStateError(f"Job not found: {handle.job_id}")
        
        job_data = self._jobs[handle.handle]
        job_status = job_data["status"]
        
        if job_status.state != "completed":
            raise JobStateError(f"Job {handle.job_id} is not completed")
        
        # Create destination directory
        Path(dest_path).mkdir(parents=True, exist_ok=True)
        
        # Create fake output file
        output_file = Path(dest_path) / f"colab_output_{handle.job_id}.json"
        output_data = {
            "job_id": handle.job_id,
            "provider": self.name,
            "status": job_status.state,
            "progress": job_status.progress,
            "completed_at": job_status.completed_at,
            "output_files": job_status.output_files,
            "metrics": {
                "runtime_hours": job_status.progress * 0.1,
                "gpu_hours": job_status.progress * 0.1,
                "training_time": job_status.progress * 2.0,
                "loss": 0.123 + (1.0 - job_status.progress / 100.0) * 0.8,
                "accuracy": 0.876 + (job_status.progress / 100.0) * 0.124
            },
            "model": {
                "size": "0.5B",
                "architecture": "Qwen2.5",
                "quantization": "4-bit",
                "training_completed": True
            }
        }
        
        with open(output_file, 'w') as f:
            import json
            json.dump(output_data, f, indent=2)
        
        job_data["output_files"].append(str(output_file))
        
        return OutputResult(
            job_id=handle.job_id,
            provider=self.name,
            output_path=str(output_file),
            output_files=job_status.output_files,
            metadata={
                "created_locally": True,
                "created_at": time.time(),
                "requires_colab_access": False
            }
        )
    
    def cancel_job(self, handle: JobHandle):
        """Cancel a Colab job."""
        if handle.handle not in self._jobs:
            raise JobStateError(f"Job not found: {handle.job_id}")
        
        job_data = self._jobs[handle.handle]
        job_status = job_data["status"]
        
        if job_status.state in ["completed", "failed"]:
            raise JobStateError(f"Cannot cancel completed job: {handle.job_id}")
        
        # In a real implementation, this would cancel the Colab runtime
        job_status.state = "cancelled"
        job_status.completed_at = time.time()
        job_status.error = "Job cancelled by user"