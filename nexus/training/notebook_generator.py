"""
Notebook generator for NEXUS training.

Generates ready-to-run Colab and Kaggle notebooks with pinned dependencies,
training scripts, Hugging Face authentication, and checkpoint saving.
"""

import json
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from nexus.core.exceptions import ProviderError
from nexus.core.logger import get_logger
from nexus.core.logger import logger as nexus_logger


class NotebookGenerator:
    """Generates training notebooks for cloud providers."""
    
    def __init__(self, config: Optional[Dict[str, Any]] = None):
        self.logger = get_logger(__name__)
        self.nexus_logger = nexus_logger
        self.config = config or {}
        
        # Notebook settings
        self.python_version = "3.13"
        self.pytorch_version = "2.11.0"
        self.transformers_version = "4.40.0"
        self.peft_version = "0.11.0"
        self.datasets_version = "2.19.0"
        self.accelerate_version = "0.31.0"
        self.bitsandbytes_version = "0.43.0"
        self.tqdm_version = "4.66.0"
    
    def generate_colab_notebook(
        self,
        job_id: str,
        model_id: str,
        dataset_id: str,
        training_config: Dict[str, Any],
        output_path: Optional[str] = None,
        use_drive: bool = False,
        hf_token_env_var: str = "HF_TOKEN",
    ) -> Dict[str, Any]:
        """Generate a Google Colab notebook for training."""
        self.nexus_logger.log_event(
            "colab_notebook_generation_start",
            {
                "job_id": job_id,
                "model_id": model_id,
                "dataset_id": dataset_id,
                "use_drive": use_drive,
            }
        )
        
        cells = []
        
        # Cell 1: Markdown header
        cells.append(self._markdown_cell(
            f"# NEXUS Training: {model_id}\n\n"
            f"**Job ID:** {job_id}\n"
            f"**Dataset:** {dataset_id}\n"
            f"**Method:** {training_config.get('method', 'qlora')}\n"
            f"**Generated:** {time.strftime('%Y-%m-%d %H:%M:%S')}\n\n"
            "This notebook was automatically generated by NEXUS for autonomous model training.\n\n"
            "## Instructions\n"
            "1. Connect to a T4 GPU (Runtime → Change runtime type → T4 GPU)\n"
            "2. Add your Hugging Face token to Colab secrets\n"
            "3. Run all cells\n"
        ))
        
        # Cell 2: Install dependencies
        cells.append(self._code_cell(
            "# Install dependencies\n"
            "!pip install -q transformers==4.40.0\n"
            "!pip install -q peft==0.11.0\n"
            "!pip install -q datasets==2.19.0\n"
            "!pip install -q accelerate==0.31.0\n"
            "!pip install -q bitsandbytes==0.43.0\n"
            "!pip install -q tqdm==4.66.0\n"
            "!pip install -q evaluate\n"
            "!pip install -q wandb\n",
            outputs=[]
        ))
        
        # Cell 3: Hugging Face authentication
        cells.append(self._code_cell(
            "# Hugging Face Authentication\n"
            "from google.colab import userdata\n"
            "from huggingface_hub import login\n"
            "\n"
            "try:\n"
            f"    hf_token = userdata.get('{hf_token_env_var}')\n"
            "    if hf_token:\n"
            "        login(token=hf_token)\n"
            "        print('✓ Hugging Face authenticated')\n"
            "    else:\n"
            "        print('⚠ No HF token found. Set it in Colab secrets.')\n"
            "except Exception as e:\n"
            "    print(f'⚠ Authentication skipped: {e}')\n"
        ))
        
        # Cell 4: Mount Google Drive (optional)
        if use_drive:
            cells.append(self._code_cell(
                "# Mount Google Drive for checkpoint storage\n"
                "from google.colab import drive\n"
                "\n"
                "try:\n"
                "    drive.mount('/content/drive')\n"
                "    print('✓ Google Drive mounted')\n"
                "except Exception as e:\n"
                "    print(f'⚠ Drive mount failed: {e}')\n"
            ))
        
        # Cell 5: Check GPU
        cells.append(self._code_cell(
            "# Check GPU availability\n"
            "import torch\n"
            "\n"
            "print(f'PyTorch version: {torch.__version__}')\n"
            "print(f'CUDA available: {torch.cuda.is_available()}')\n"
            "\n"
            "if torch.cuda.is_available():\n"
            "    print(f'GPU: {torch.cuda.get_device_name(0)}')\n"
            "    print(f'GPU memory: {torch.cuda.get_device_properties(0).total_memory / 1e9:.1f} GB')\n"
            "else:\n"
            "    print('⚠ No GPU detected. Training will be slow on CPU.')\n"
        ))
        
        # Cell 6: Training script
        training_code = self._generate_training_code(
            model_id=model_id,
            dataset_id=dataset_id,
            training_config=training_config,
        )
        cells.append(self._code_cell(training_code))
        
        # Cell 7: Save results
        cells.append(self._code_cell(
            "# Save training results\n"
            "import json\n"
            "from pathlib import Path\n"
            "\n"
            "results = {\n"
            "    'job_id': '" + job_id + "',\n"
            "    'model_id': '" + model_id + "',\n"
            "    'dataset_id': '" + dataset_id + "',\n"
            "    'method': '" + str(training_config.get('method', 'qlora')) + "',\n"
            "    'completed_at': __import__('time').time(),\n"
            "}\n"
            "\n"
            "results_path = Path('/content/training_results.json')\n"
            "with open(results_path, 'w') as f:\n"
            "    json.dump(results, f, indent=2)\n"
            "\n"
            "print(f'✓ Results saved to {results_path}')\n"
            "print(f'Model adapter saved to ./outputs/')\n"
        ))
        
        notebook = {
            "cells": cells,
            "metadata": {
                "kernelspec": {
                    "display_name": "Python 3",
                    "language": "python",
                    "name": "python3"
                },
                "language_info": {
                    "name": "python",
                    "version": "3.13.16"
                },
                "colab": {
                    "name": f"NEXUS {job_id}",
                    "provenance": {}
                },
                "accelerator": "GPU",
                "gpuType": "T4"
            },
            "nbformat": 4,
            "nbformat_minor": 4
        }
        
        # Save if output path provided
        if output_path:
            output_file = Path(output_path)
            output_file.parent.mkdir(parents=True, exist_ok=True)
            with open(output_file, 'w') as f:
                json.dump(notebook, f, indent=2)
        
        self.nexus_logger.log_event(
            "colab_notebook_generation_completed",
            {
                "job_id": job_id,
                "cells": len(cells),
                "output_path": output_path,
            }
        )
        
        return {
            "job_id": job_id,
            "provider": "colab",
            "notebook": notebook,
            "output_path": output_path,
            "instructions": [
                "1. Open this notebook in Google Colab",
                "2. Connect to T4 GPU runtime",
                "3. Add HF_TOKEN to Colab secrets (left sidebar → key icon)",
                "4. Run all cells",
                "5. Download adapter from ./outputs/ when complete"
            ]
        }
    
