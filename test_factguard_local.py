import os
import sys
import json

print("=== Starting FactGuard-SLM Local Inference Test ===")

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
from peft import PeftModel

BASE_MODEL = "Qwen/Qwen2.5-1.5B-Instruct"
ADAPTER_PATH = "/home/sriharish00u/Desktop/projects/NEXUS/models/factguard_adapter/factguard_adapter"

print("--> 1. Loading Tokenizer...")
tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, trust_remote_code=True)

print("--> 2. Loading Base Model in bfloat16 on CPU (low RAM footprint)...")
base_model = AutoModelForCausalLM.from_pretrained(
    BASE_MODEL,
    torch_dtype=torch.bfloat16,
    low_cpu_mem_usage=True,
    device_map="cpu",
    trust_remote_code=True
)

print(f"--> 3. Attaching Trained LoRA Adapter from: {ADAPTER_PATH}")
model = PeftModel.from_pretrained(base_model, ADAPTER_PATH)
model.eval()

def query_factguard(system_prompt, user_content):
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content}
    ]
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(prompt, return_tensors="pt")
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=300,
            temperature=0.1,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id
        )
    return tokenizer.decode(out[0][inputs.input_ids.shape[1]:], skip_special_tokens=True)

print("\n" + "="*70)
print("TEST 1: DECOMPOSITION (Raw text -> Atomic Claims + Search Queries)")
print("="*70)

raw_text = (
    "Apollo 11 landed on the moon on July 20, 1969, and Michael Collins walked on the lunar "
    "surface with Neil Armstrong while Buzz Aldrin stayed in orbit."
)
print("Input Text:", raw_text)

sys_decomposer = (
    "You are FactGuard Decomposer. Given an input text generated by an AI assistant, "
    "break down the assertions into verifiable atomic claims. For each claim, output a "
    "focused search query to retrieve authoritative evidence."
)
stage1_res = query_factguard(sys_decomposer, f"Decompose the following text into atomic claims and generate research queries:\n\n{raw_text}")
print("\nFactGuard JSON Output:")
print(stage1_res)

print("\n" + "="*70)
print("TEST 2: EVALUATION & CORRECTION (Claims + Evidence -> Verdict + Patch)")
print("="*70)

claims_and_evidence = {
    "claims": [
        {
            "claim_id": "c1",
            "claim": "Michael Collins walked on the lunar surface with Neil Armstrong.",
            "evidence": "Neil Armstrong and Buzz Aldrin were the two astronauts who walked on the Moon. Michael Collins flew the Command Module Columbia alone in lunar orbit."
        }
    ]
}

sys_evaluator = (
    "You are FactGuard Evaluator & Correction Gate. Analyze atomic claims alongside retrieved evidence. "
    "For each claim, decide status: SUPPORTED, CONTRADICTED, or UNVERIFIABLE. "
    "If any claim is CONTRADICTED, provide a structured prompt patch explaining the hallucination "
    "and directing the external model how to regenerate accurately."
)
stage2_res = query_factguard(sys_evaluator, f"Evaluate the following claims against the provided evidence and determine if any hallucination occurred:\n\n{json.dumps(claims_and_evidence, indent=2)}")
print("\nFactGuard Evaluator Output:")
print(stage2_res)
print("\n=== Local Test Completed Successfully! ===")
